function reconcileGroupOrders(app, settings) {
  let changed = false;
  const groupPaths = new Set(settings.groups.map((g) => g.path));
  for (const group of settings.groups) {
    const folder = getFolder(app, group.path);
    if (!folder)
      continue;
    if (group.name !== folder.name) {
      group.name = folder.name;
      changed = true;
    }
    const children = folder.children.filter(
      (c) => c instanceof import_obsidian3.TFolder && !groupPaths.has(c.path) && !isHiddenFolder(c.name)
    ).map((c) => c.path).sort((a, b) => baseNameOf(a).localeCompare(baseNameOf(b), "zh"));
    const next = group.order.filter((p) => children.includes(p));
    for (const p of children)
      if (!next.includes(p))
        next.push(p);
    if (next.length !== group.order.length || next.some((p, i) => p !== group.order[i])) {
      group.order = next;
      changed = true;
    }
  }
  const rootKbs = app.vault.getRoot().children.filter(
    (c) => c instanceof import_obsidian3.TFolder && !groupPaths.has(c.path) && !isHiddenFolder(c.name)
  ).map((c) => c.path).sort((a, b) => baseNameOf(a).localeCompare(baseNameOf(b), "zh"));
  const nextUngrouped = settings.ungroupedOrder.filter((p) => rootKbs.includes(p));
  for (const p of rootKbs)
    if (!nextUngrouped.includes(p))
      nextUngrouped.push(p);
  if (nextUngrouped.length !== settings.ungroupedOrder.length || nextUngrouped.some((p, i) => p !== settings.ungroupedOrder[i])) {
    settings.ungroupedOrder = nextUngrouped;
    changed = true;
  }
  return changed;
}
function remapPath(path, oldPath, newPath) {
  if (path === oldPath)
    return newPath;
  if (path.startsWith(oldPath + "/"))
    return newPath + path.slice(oldPath.length);
  return path;
}
function migrateSettingsPaths(settings, oldPath, newPath) {
  if (!oldPath || oldPath === newPath)
    return false;
  let changed = false;
  const overrides = {};
  for (const [path, value] of Object.entries(settings.overrides)) {
    const next = remapPath(path, oldPath, newPath);
    if (next !== path)
      changed = true;
    overrides[next] = value;
  }
  settings.overrides = overrides;
  for (const group of settings.groups) {
    const next = remapPath(group.path, oldPath, newPath);
    if (next !== group.path) {
      group.path = next;
      group.name = baseNameOf(next);
      changed = true;
    }
  }
  for (const group of settings.groups) {
    const next = group.order.map((p) => remapPath(p, oldPath, newPath));
    if (next.some((p, i) => p !== group.order[i])) {
      group.order = next;
      changed = true;
    }
  }
  const nextUngrouped = settings.ungroupedOrder.map(
    (p) => remapPath(p, oldPath, newPath)
  );
  if (nextUngrouped.some((p, i) => p !== settings.ungroupedOrder[i])) {
    settings.ungroupedOrder = nextUngrouped;
    changed = true;
  }
  const items = {};
  for (const [path, value] of Object.entries(settings.order.items)) {
    const next = remapPath(path, oldPath, newPath);
    if (next !== path)
      changed = true;
    items[next] = value;
  }
  settings.order.items = items;
  const oldName = baseNameOf(oldPath);
  const newName = baseNameOf(newPath);
  const oldParentPath = parentPathOf(oldPath);
  const newParentPath = parentPathOf(newPath);
  const oldParent = settings.order.items[oldParentPath];
  if (isFolderSettings(oldParent)) {
    const idx = oldParent.customOrder.indexOf(oldName);
    if (idx !== -1) {
      if (oldParentPath === newParentPath)
        oldParent.customOrder[idx] = newName;
      else
        oldParent.customOrder.splice(idx, 1);
      changed = true;
    }
  }
  if (oldParentPath !== newParentPath) {
    const newParent = settings.order.items[newParentPath];
    if (isFolderSettings(newParent) && !newParent.customOrder.includes(newName)) {
      newParent.customOrder.push(newName);
      changed = true;
    }
  }
  return changed;
}
